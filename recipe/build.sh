#!/bin/bash

# LIBVERSION shall only include MAJOR.MINOR.PATCH for require
LIBVERSION=$(echo ${PKG_VERSION}| cut -d'.' -f1-3)

if [[ "$EPICS_TARGET_ARCH" == "linux-ppc64e6500" ]]
then
  DRV_USBTMC=NO
  TIRPC=YES
else
  DRV_USBTMC=YES
  TIRPC=NO
fi

# Clean between variants builds
make clean

make DRV_USBTMC=$DRV_USBTMC TIRPC=$TIRPC MODULE=${PKG_NAME} LIBVERSION=${LIBVERSION}
make DRV_USBTMC=$DRV_USBTMC TIRPC=$TIRPC MODULE=${PKG_NAME} LIBVERSION=${LIBVERSION} db
make DRV_USBTMC=$DRV_USBTMC TIRPC=$TIRPC MODULE=${PKG_NAME} LIBVERSION=${LIBVERSION} install

