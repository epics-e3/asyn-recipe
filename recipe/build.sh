#!/bin/bash

LIBVERSION=${PKG_VERSION}

if [[ "$EPICS_TARGET_ARCH" == "linux-ppc64e6500" ]]
then
  DRV_USBTMC=NO
else
  DRV_USBTMC=YES
fi
TIRPC=YES

# Clean between variants builds
make clean

make DRV_USBTMC=$DRV_USBTMC TIRPC=$TIRPC MODULE=${PKG_NAME} LIBVERSION=${LIBVERSION}
make DRV_USBTMC=$DRV_USBTMC TIRPC=$TIRPC MODULE=${PKG_NAME} LIBVERSION=${LIBVERSION} db_internal
make DRV_USBTMC=$DRV_USBTMC TIRPC=$TIRPC MODULE=${PKG_NAME} LIBVERSION=${LIBVERSION} install

